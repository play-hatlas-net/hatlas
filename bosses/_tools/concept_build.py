"""Helper to write a character's concept/concept.yml from a short Python description.

A concept is a list of boxes (format: concept_sheet.py header). Writing ~100 boxes by hand is error
prone, so each character keeps a small `concept/design.py` that uses this helper (mirrored limbs,
stacked cap layers, decals) and writes `concept/concept.yml`. The yml stays the file every other tool
reads.

Units: pixels (1/16 block). y up from the ground, the character faces -z, its right side is +x.

Usage (from a design.py):
    c = Concept()
    c.note("legs")
    c.sym("leg_{s}", 2, 25, -1, 3, 6, 3, "bark")      # right box + its mirror, {s} = r / l
    c.box("head", -16, 58, -13, 32, 3, 24, "cap_deep")
    c.fz("body", 1, 48, 2, 4, -4, "cyan_glow")        # decal on the plane z = -4
    c.write(Path(__file__).with_name("concept.yml"), "Fungal Root")
"""
from __future__ import annotations

from pathlib import Path


class Concept:
    def __init__(self):
        self.items: list = []

    def note(self, text: str):
        self.items.append(text)

    def box(self, bone, x, y, z, w, h, d, color, paint=False):
        part = {"bone": bone, "from": [x, y, z], "size": [w, h, d], "color": color}
        if paint:
            part["paint"] = True
        self.items.append(part)

    def paint(self, bone, x, y, z, w, h, d, color):
        """A texture detail given as a volume (drawn over the cube it lies on, not counted as a cube)."""
        self.box(bone, x, y, z, w, h, d, color, paint=True)

    def sym(self, bone, x, y, z, w, h, d, color, paint=False):
        """A box on the right side (+x) and its mirror on the left. `{s}` in the bone name = r / l."""
        self.box(bone.format(s="r"), x, y, z, w, h, d, color, paint)
        self.box(bone.format(s="l"), -(x + w), y, z, w, h, d, color, paint)

    def fz(self, bone, x, y, w, h, z, color):
        """Decal on a plane z = const (a front or back face)."""
        self.box(bone, x, y, z, w, h, 0, color, paint=True)

    def fx(self, bone, z, y, d, h, x, color):
        """Decal on a plane x = const (a side face)."""
        self.box(bone, x, y, z, 0, h, d, color, paint=True)

    @property
    def cubes(self) -> int:
        return sum(1 for p in self.items if isinstance(p, dict) and not p.get("paint"))

    def write(self, path: Path, title: str):
        lines = [
            f"# {title}: concept as boxes. GENERATED by concept/design.py (edit that file, then run it);",
            "# drawn by bosses/_tools/concept_sheet.py (format in its header).",
            "# Pixels (1/16 block). y up from the ground, it faces -z, its right side is +x.",
            f"# `paint: true` = detail painted on the texture (not a cube). {self.cubes} cubes.",
            "parts:",
        ]
        for it in self.items:
            if isinstance(it, str):
                lines.append(f"  # --- {it}")
                continue
            s = "  - {bone: %s, from: [%d, %d, %d], size: [%d, %d, %d], color: %s" % (
                it["bone"], *it["from"], *it["size"], it["color"])
            lines.append(s + (", paint: true}" if it.get("paint") else "}"))
        Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{path}: {self.cubes} cubes, {len([i for i in self.items if isinstance(i, dict)]) - self.cubes} painted details")
